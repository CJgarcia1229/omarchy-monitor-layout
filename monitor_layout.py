    def identify_displays(self, _button):
        display = Gdk.Display.get_default()
        if display is None:
            self.status.set_label("Could not access the active graphical display.")
            return

        outputs = {monitor["name"]: index + 1 for index, monitor in enumerate(self.monitors)}
        windows = []
        model = display.get_monitors()
        for index in range(model.get_n_items()):
            gdk_monitor = model.get_item(index)
            connector = gdk_monitor.get_connector() or f"Display {index + 1}"
            number = outputs.get(connector, index + 1)
            window = IdentificationWindow(self.get_application(), gdk_monitor, number, connector)
            windows.append(window)
            window.present()

        # Keep references alive until the windows close after four seconds.
        self._identification_windows = windows

        def close_identifiers():
            for window in self._identification_windows:
                window.close()
            self._identification_windows = []
            return GLib.SOURCE_REMOVE

        GLib.timeout_add_seconds(4, close_identifiers)
        self.status.set_label("Display identifiers shown for four seconds.")

    def selection_changed(self, monitor):
        self.name_label.set_label(monitor["description"])
        self.x_spin.handler_block_by_func(self.coordinate_changed)
        self.y_spin.handler_block_by_func(self.coordinate_changed)
        self.x_spin.set_value(monitor["x"])
        self.y_spin.set_value(monitor["y"])
        self.x_spin.handler_unblock_by_func(self.coordinate_changed)
        self.y_spin.handler_unblock_by_func(self.coordinate_changed)
        modes = monitor.get("availableModes", [])
        labels = [mode["label"] for mode in modes]
        self.mode_dropdown.handler_block_by_func(self.mode_changed)
        self.mode_dropdown.set_model(Gtk.StringList.new(labels))
        selected = 0
        for index, mode in enumerate(modes):
            if (mode["width"] == monitor["width"] and mode["height"] == monitor["height"]
                    and abs(mode["refreshRate"] - monitor["refreshRate"]) < 0.01):
                selected = index
                break
        self.mode_dropdown.set_selected(selected if modes else Gtk.INVALID_LIST_POSITION)
        self.mode_dropdown.set_sensitive(bool(modes))
        self.mode_dropdown.handler_unblock_by_func(self.mode_changed)

        scales = list(COMMON_SCALES)
        if not any(abs(scale - monitor["scale"]) < 0.001 for scale in scales):
            scales.append(monitor["scale"])
            scales.sort()
        self._visible_scales = scales
        self.scale_dropdown.handler_block_by_func(self.scale_changed)
        self.scale_dropdown.set_model(Gtk.StringList.new([f"{scale:g}×" for scale in scales]))
        selected_scale = min(range(len(scales)), key=lambda index: abs(scales[index] - monitor["scale"]))
        self.scale_dropdown.set_selected(selected_scale)
        self.scale_dropdown.handler_unblock_by_func(self.scale_changed)

    def coordinate_changed(self, _spin):
        monitor = self.monitors[self.canvas.selected]
        monitor["x"] = self.x_spin.get_value_as_int()
        monitor["y"] = self.y_spin.get_value_as_int()
        self.canvas.queue_draw()

    def mode_changed(self, dropdown, _param):
        monitor = self.monitors[self.canvas.selected]
        modes = monitor.get("availableModes", [])
        selected = dropdown.get_selected()
        if selected == Gtk.INVALID_LIST_POSITION or selected >= len(modes):
            return
        mode = modes[selected]
        monitor["width"] = mode["width"]
        monitor["height"] = mode["height"]
        monitor["refreshRate"] = mode["refreshRate"]
        self.canvas.queue_draw()
        self.status.set_label(f'{monitor["name"]}: {mode["label"]} selected.')

    def scale_changed(self, dropdown, _param):
        selected = dropdown.get_selected()
        if selected == Gtk.INVALID_LIST_POSITION or selected >= len(self._visible_scales):
            return
        monitor = self.monitors[self.canvas.selected]
        monitor["scale"] = self._visible_scales[selected]
        logical_width, logical_height = logical_size(monitor)
        self.canvas.queue_draw()
        self.status.set_label(
            f'{monitor["name"]}: {monitor["scale"]:g}× scale '
            f'({logical_width}×{logical_height} logical workspace).'
        )

    def normalize(self):
        min_x = min(m["x"] for m in self.monitors)
        min_y = min(m["y"] for m in self.monitors)
        for monitor in self.monitors:
            monitor["x"] -= min_x
            monitor["y"] -= min_y

    def preview(self, _button):
        try:
            self.normalize()
            for monitor in self.monitors:
                refresh = f'{monitor["refreshRate"]:.3f}'.rstrip("0").rstrip(".")
                rule = f'{monitor["name"]},{monitor["width"]}x{monitor["height"]}@{refresh},{monitor["x"]}x{monitor["y"]},{monitor["scale"]:g}'
                if monitor["transform"]:
                    rule += f',transform,{monitor["transform"]}'
                run("hyprctl", "keyword", "monitor", rule)
            self.status.set_label("Preview applied. Save to keep it after logout.")
            self.canvas.queue_draw()
            self.selection_changed(self.monitors[self.canvas.selected])
        except Exception as exc:
            self.status.set_label(f"Preview failed: {exc}")

    def save(self, _button):
        try:
            self.normalize()
            CONFIG.parent.mkdir(parents=True, exist_ok=True)
            backup = None
            if CONFIG.exists():
                backup = CONFIG.with_name(f"{CONFIG.name}.bak.{int(time.time())}")
                shutil.copy2(CONFIG, backup)
            content = HEADER + "\n".join(monitor_rule(m) for m in self.monitors) + "\n"
            temp = CONFIG.with_suffix(".lua.tmp")
            temp.write_text(content)
            temp.replace(CONFIG)
            reload_result = run("hyprctl", "reload", check=False)
            errors = run("hyprctl", "configerrors", check=False)
            if reload_result.returncode or errors.stdout.strip():
                if backup:
                    shutil.copy2(backup, CONFIG)
                    run("hyprctl", "reload", check=False)
                raise RuntimeError(errors.stdout.strip() or reload_result.stderr.strip())
            suffix = f" Backup: {backup}" if backup else ""
            self.status.set_label("Layout saved and Hyprland reloaded." + suffix)
        except Exception as exc:
            self.status.set_label(f"Save failed; previous config restored: {exc}")

    def reset(self, _button):
        self.monitors[:] = json.loads(json.dumps(self.original))
        self.canvas.selected = 0
        self.selection_changed(self.monitors[0])
        self.canvas.queue_draw()
        self.status.set_label("Reset to the layout detected when this window opened.")


