def rgb(hex_color: str) -> tuple[float, float, float]:
    value = hex_color.lstrip("#")
    return tuple(int(value[index:index + 2], 16) / 255 for index in (0, 2, 4))


def run(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, text=True, capture_output=True, check=check)


def output_selector(item: dict, raw: list[dict]) -> str:
    description = item.get("description") or ""
    others = [other.get("description") or "" for other in raw if other is not item]
    ambiguous = any(
        other.startswith(description) or description.startswith(other)
        for other in others
        if other
    )
    if not description or ambiguous:
        return item["name"]
    return f"desc:{description}"


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_monitors() -> list[dict]:
    try:
        raw = json.loads(run("hyprctl", "monitors", "all", "-j").stdout)
    except (FileNotFoundError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"Could not read monitors from Hyprland: {exc}") from exc

    monitors = []
    for item in raw:
        if item.get("disabled"):
            continue
        modes = parse_modes(item.get("availableModes", []))
        current_width = int(item.get("width", 1920))
        current_height = int(item.get("height", 1080))
        current_refresh = float(item.get("refreshRate", 60.0))
        # "Best" follows the display-settings convention: maximize pixel
        # area first, then refresh rate among modes at that resolution.
        best_mode = max(modes, key=lambda mode: (mode["width"] * mode["height"], mode["refreshRate"]), default=None)
        if best_mode:
            current_width = best_mode["width"]
            current_height = best_mode["height"]
            current_refresh = best_mode["refreshRate"]
        monitors.append({
            "name": item["name"],
            "output": output_selector(item, raw),
            "description": item.get("description") or item["name"],
            "width": current_width,
            "height": current_height,
            "refreshRate": current_refresh,
            "availableModes": modes,
            "x": int(item.get("x", 0)),
            "y": int(item.get("y", 0)),
            "scale": float(item.get("scale", 1.0)),
            "transform": int(item.get("transform", 0)),
            "focused": bool(item.get("focused", False)),
        })
    if not monitors:
        raise RuntimeError("Hyprland reported no enabled monitors.")
    return monitors


MODE_PATTERN = re.compile(r"^(\d+)x(\d+)@([0-9.]+)(?:Hz)?$")


def parse_modes(raw_modes: list[str]) -> list[dict]:
    modes = []
    seen = set()
    for raw_mode in raw_modes:
        match = MODE_PATTERN.match(str(raw_mode).strip())
        if not match:
            continue
        width, height = int(match.group(1)), int(match.group(2))
        refresh = float(match.group(3))
        key = (width, height, round(refresh, 3))
        if key in seen:
            continue
        seen.add(key)
        modes.append({
            "width": width,
            "height": height,
            "refreshRate": refresh,
            "label": f"{width} × {height}  @  {refresh:g} Hz",
        })
    modes.sort(key=lambda mode: (mode["width"] * mode["height"], mode["refreshRate"]), reverse=True)
    return modes


def logical_size(monitor: dict) -> tuple[int, int]:
    width, height = monitor["width"], monitor["height"]
    if monitor["transform"] in (1, 3, 5, 7):
        width, height = height, width
    return round(width / monitor["scale"]), round(height / monitor["scale"])


def monitor_rule(monitor: dict) -> str:
    refresh = f'{monitor["refreshRate"]:.3f}'.rstrip("0").rstrip(".")
    mode = f'{monitor["width"]}x{monitor["height"]}@{refresh}'
    scale = f'{monitor["scale"]:g}'
    parts = [
        f'output = {lua_string(monitor["output"])}',
        f'mode = "{mode}"',
        f'position = "{monitor["x"]}x{monitor["y"]}"',
        f'scale = {scale}',
    ]
    if monitor["transform"]:
        parts.append(f'transform = {monitor["transform"]}')
    return "hl.monitor({ " + ", ".join(parts) + " })"


class LayoutCanvas(Gtk.DrawingArea):
    PADDING = 34
    # Windows Display Settings behaves like magnetic edge docking: displays
    # move freely until two physical edges are close on screen, then touch.
    # Keep this in canvas pixels so the feel is stable at every zoom level.
    SNAP_PIXELS = 18
    # Along an already connected edge, expose the familiar three placement
    # anchors: start, center, and end. A slightly wider zone makes a smaller
    # 1920x1080 display easy to center beneath a larger primary display.
    ALIGN_PIXELS = 18

    def __init__(self, monitors: list[dict], changed_callback):
        super().__init__()
        self.monitors = monitors
        self.changed_callback = changed_callback
        self.selected = 0
        self.drag_origin = None
        self.drag_scale = None
        self.set_content_width(760)
        self.set_content_height(420)
        self.set_hexpand(True)
        self.set_vexpand(True)
        self.set_draw_func(self.draw)

        click = Gtk.GestureClick.new()
        click.connect("pressed", self.on_pressed)
        click.connect("released", self.on_released)
        self.add_controller(click)

        drag = Gtk.GestureDrag.new()
        drag.connect("drag-begin", self.on_drag_begin)
        drag.connect("drag-update", self.on_drag_update)
        drag.connect("drag-end", self.on_drag_end)
        self.add_controller(drag)

    def bounds(self):
        left = min(m["x"] for m in self.monitors)
        top = min(m["y"] for m in self.monitors)
        right = max(m["x"] + logical_size(m)[0] for m in self.monitors)
        bottom = max(m["y"] + logical_size(m)[1] for m in self.monitors)
        return left, top, right, bottom

    def transform(self, width, height):
        left, top, right, bottom = self.bounds()
        scale = min(
            (width - self.PADDING * 2) / max(1, right - left),
            (height - self.PADDING * 2) / max(1, bottom - top),
        )
        scale = min(scale, 0.22)
        ox = (width - (right - left) * scale) / 2 - left * scale
        oy = (height - (bottom - top) * scale) / 2 - top * scale
        return scale, ox, oy

    def rect_for(self, monitor, width=None, height=None):
        width = width or self.get_width()
        height = height or self.get_height()
        scale, ox, oy = self.transform(width, height)
        lw, lh = logical_size(monitor)
        return monitor["x"] * scale + ox, monitor["y"] * scale + oy, lw * scale, lh * scale

    def monitor_at(self, x, y):
        for index in range(len(self.monitors) - 1, -1, -1):
            rx, ry, rw, rh = self.rect_for(self.monitors[index])
            if rx <= x <= rx + rw and ry <= y <= ry + rh:
                return index
        return None

    def draw(self, area, cr, width, height):
        cr.set_source_rgb(*rgb(THEME["dark_background"]))
        cr.paint()

        # Quiet coordinate grid, matching Omarchy's technical/terminal visual
        # language without competing with the monitor cards.
        cr.set_source_rgba(*rgb(THEME["foreground"]), 0.035)
        cr.set_line_width(1)
        for gx in range(20, width, 28):
            cr.move_to(gx, 0)
            cr.line_to(gx, height)
        for gy in range(20, height, 28):
            cr.move_to(0, gy)
            cr.line_to(width, gy)
        cr.stroke()

        for index, monitor in enumerate(self.monitors):
            x, y, w, h = self.rect_for(monitor, width, height)
            if index == self.selected:
                cr.set_source_rgba(*rgb(THEME["accent"]), 0.28)
            else:
                cr.set_source_rgb(*rgb(THEME["lighter_background"]))
            cr.rectangle(x, y, w, h)
            cr.fill_preserve()
            cr.set_line_width(3 if index == self.selected else 1.5)
            cr.set_source_rgb(*rgb(THEME["accent"] if index == self.selected else THEME["dark_foreground"]))
            cr.stroke()
            cr.set_source_rgb(*rgb(THEME["foreground"]))
            cr.select_font_face("JetBrainsMono Nerd Font", 0, 1)
            cr.set_font_size(14)
            cr.move_to(x + 12, y + 25)
            cr.show_text(f'{index + 1}  {monitor["name"]}')
            cr.set_font_size(11)
            cr.move_to(x + 12, y + 44)
            lw, lh = logical_size(monitor)
            refresh = f'{monitor["refreshRate"]:g}'
            cr.show_text(f'{monitor["width"]}×{monitor["height"]} @ {refresh} Hz')
            cr.move_to(x + 12, y + 61)
            if monitor["scale"] != 1:
                cr.show_text(f'{lw}×{lh} logical · {monitor["scale"]:g}× scale · ({monitor["x"]}, {monitor["y"]})')
            else:
                cr.show_text(f'({monitor["x"]}, {monitor["y"]})')

    def on_pressed(self, gesture, presses, x, y):
        index = self.monitor_at(x, y)
        if index is not None:
            self.selected = index
            self.changed_callback(self.monitors[index])
            self.queue_draw()

    def on_released(self, *_args):
        pass

    def on_drag_begin(self, gesture, x, y):
        index = self.monitor_at(x, y)
        if index is None:
            self.drag_origin = None
            return
        self.selected = index
        monitor = self.monitors[index]
        self.drag_origin = (monitor["x"], monitor["y"])
        self.drag_scale = self.transform(self.get_width(), self.get_height())[0]
        self.changed_callback(monitor)

    @staticmethod
    def ranges_overlap(start_a, size_a, start_b, size_b, tolerance=0):
        return start_a < start_b + size_b + tolerance and start_a + size_a > start_b - tolerance

    def snap_position(self, monitor, x, y, dx, dy):
        """Dock nearby display edges, closely matching Windows' layout UI."""
        width, height = logical_size(monitor)
        scale = self.drag_scale or 1
        dock_distance = self.SNAP_PIXELS / scale
        align_distance = self.ALIGN_PIXELS / scale
        horizontal_docks = []
        vertical_docks = []

        for other in self.monitors:
            if other is monitor:
                continue
            other_width, other_height = logical_size(other)
            ox, oy = other["x"], other["y"]

            # Only facing edges dock. Merely sharing a left edge or center
            # should never pull a display across the canvas.
            if self.ranges_overlap(y, height, oy, other_height, dock_distance):
                horizontal_docks.extend([
                    (abs((x + width) - ox), ox - width),
                    (abs(x - (ox + other_width)), ox + other_width),
                ])
            if self.ranges_overlap(x, width, ox, other_width, dock_distance):
                vertical_docks.extend([
                    (abs((y + height) - oy), oy - height),
                    (abs(y - (oy + other_height)), oy + other_height),
                ])

        docked_x = False
        docked_y = False
        if horizontal_docks:
            distance, value = min(horizontal_docks, key=lambda item: item[0])
            if distance <= dock_distance:
                x, docked_x = value, True
        if vertical_docks:
            distance, value = min(vertical_docks, key=lambda item: item[0])
            if distance <= dock_distance:
                y, docked_y = value, True

        # Once docked, lightly align the ends of the shared edge. The display
        # remains freely slideable everywhere else along that edge.
        for other in self.monitors:
            if other is monitor:
                continue
            other_width, other_height = logical_size(other)
            if docked_x:
                for candidate in (
                    other["y"],
                    round(other["y"] + (other_height - height) / 2),
                    other["y"] + other_height - height,
                ):
                    if abs(y - candidate) <= align_distance:
                        y = candidate
                        break
            if docked_y:
                for candidate in (
                    other["x"],
                    round(other["x"] + (other_width - width) / 2),
                    other["x"] + other_width - width,
                ):
                    if abs(x - candidate) <= align_distance:
                        x = candidate
                        break

        # Displays in the Windows widget cannot be left overlapping. Resolve
        # an overlap on the drag's dominant axis, in its direction of travel.
        for other in self.monitors:
            if other is monitor:
                continue
            other_width, other_height = logical_size(other)
            ox, oy = other["x"], other["y"]
            overlap_x = min(x + width, ox + other_width) - max(x, ox)
            overlap_y = min(y + height, oy + other_height) - max(y, oy)
            if overlap_x > 0 and overlap_y > 0:
                if abs(dx) >= abs(dy):
                    x = ox - width if dx >= 0 else ox + other_width
                else:
                    y = oy - height if dy >= 0 else oy + other_height
        return x, y

    def on_drag_update(self, gesture, dx, dy):
        if self.drag_origin is None:
            return
        scale = self.drag_scale or self.transform(self.get_width(), self.get_height())[0]
        monitor = self.monitors[self.selected]
        x = round((self.drag_origin[0] + dx / scale) / 10) * 10
        y = round((self.drag_origin[1] + dy / scale) / 10) * 10
        monitor["x"], monitor["y"] = self.snap_position(monitor, x, y, dx, dy)
        self.changed_callback(monitor)
        self.queue_draw()

    def on_drag_end(self, *_args):
        self.drag_origin = None
        self.drag_scale = None


class IdentificationWindow(Gtk.Window):
    def __init__(self, app, monitor, number, output_name):
        super().__init__(application=app, title=f"Display {number}")
        self.set_decorated(False)
        self.set_resizable(False)
        self.add_css_class("identifier")

        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=12)
        box.set_halign(Gtk.Align.CENTER)
        box.set_valign(Gtk.Align.CENTER)
        number_label = Gtk.Label(label=str(number))
        number_label.add_css_class("identifier-number")
        name_label = Gtk.Label(label=output_name)
        name_label.add_css_class("identifier-name")
        hint = Gtk.Label(label="This label closes automatically")
        hint.add_css_class("dim-label")
        box.append(number_label)
        box.append(name_label)
        box.append(hint)
        self.set_child(box)
        self.fullscreen_on_monitor(monitor)

        click = Gtk.GestureClick.new()
        click.connect("pressed", lambda *_args: self.close())
        self.add_controller(click)


